// Copies the chat assistant's rule engine out of an AI Studio export's server.ts into
// src/lib/ruleEngine.ts, so the browser runs exactly the same rules as the original server.
//
//   node scripts/sync-rule-engine.mjs ../feasibility_initial_20_11/server.ts
//
// The function body is copied verbatim; only the header and import paths are generated.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const serverTs = process.argv[2];
if (!serverTs) {
  console.error('Usage: node scripts/sync-rule-engine.mjs <path to AI Studio server.ts>');
  process.exit(1);
}

const source = readFileSync(serverTs, 'utf8');
const start = source.indexOf('function processRuleBasedQuery(');
const end = source.indexOf('// REST route for Chat');
if (start < 0 || end < 0 || end < start) {
  console.error('Could not find processRuleBasedQuery() followed by the "// REST route for Chat" marker.');
  process.exit(1);
}

// Imports of the original server, re-pointed from the project root to src/lib/.
const imports = [...source.slice(0, start).matchAll(/^import\s+\{[^}]*\}\s+from\s+["']\.\/src\/([^"']+)["'];?$/gm)]
  .map((m) => m[0].replace(/["']\.\/src\/([^"']+)["']/, (_q, p) => `'${p.startsWith('lib/') ? './' + p.slice(4) : '../' + p}'`));

const body = source.slice(start, end).trimEnd();
const output = `// GENERATED by scripts/sync-rule-engine.mjs from ${path.basename(path.dirname(path.resolve(serverTs)))}/server.ts.
// Do not edit by hand: re-run the script when a new AI Studio export arrives.
//
// The original Express server answered chat messages with this function on POST /api/chat.
// The Flask version runs it in the browser instead (see ChatPane.tsx), so the rules stay
// identical to the original and the shared database is not uploaded with every message.
${imports.join('\n')}

export ${body}
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'ruleEngine.ts');
writeFileSync(target, output);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${body.split('\n').length} lines of rule engine)`);
