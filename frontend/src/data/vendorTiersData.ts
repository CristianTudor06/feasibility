/**
 * Fast lookup map by lowercased vendor name (e.g. "vendor 1" -> { name, tier, color })
 */
export const VENDOR_TIERS_MAP = new Map<string, VendorTier>(
  ATTACHED_VENDOR_TIERS.map(v => [v.name.toLowerCase().trim(), v])
);

/**
 * Returns the authoritative tier configuration for a vendor by name or index.
 */
export function getAuthoritativeVendorConfig(vendorNameOrNumber: string | number): VendorTier {
  const cleanName = typeof vendorNameOrNumber === 'number'
    ? `vendor ${vendorNameOrNumber}`
    : String(vendorNameOrNumber).toLowerCase().trim();
  
  const found = VENDOR_TIERS_MAP.get(cleanName);
  if (found) {
    return { ...found };
  }
  // Try extracting number
  const numMatch = cleanName.match(/\d+/);
  if (numMatch) {
    const byNum = VENDOR_TIERS_MAP.get(`vendor ${parseInt(numMatch[0], 10)}`);
    if (byNum) return { ...byNum };
  }
  return {
    name: typeof vendorNameOrNumber === 'number' ? `Vendor ${vendorNameOrNumber}` : String(vendorNameOrNumber),
    tier: 'No Tier',
    color: 'Grey'
  };
}
